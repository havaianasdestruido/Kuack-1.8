/*
 * The mipmap box filter used by TextureUtil.generateMipmapData, split out of TextureUtil so the
 * arithmetic can be exercised without bringing up the GL texture stack (TextureUtil's static
 * initialiser allocates a 16 MiB direct buffer and a DynamicTexture, so it cannot even be loaded on
 * a plain JVM).
 *
 * What it does: four neighbouring 8-bit-per-channel texels are averaged. Vanilla does the average in
 * linear light when the sprite has transparency (the gamma-correct box filter, the "flag" branch) and
 * in a slightly cheaper form otherwise; both branches decode every channel byte with
 *   (float) Math.pow((float) (v & 255) / 255.0F, 2.2)
 * and encode the result with Math.pow(avg, 1 / 2.2).
 *
 * Why a table: the decode step has exactly 256 distinct inputs (one per byte value) and runs up to 20
 * times per output texel (4 channels x 4 neighbours in the gamma branch, 4 channels in the linear
 * branch). That makes it an ideal integer-indexed lookup: a 256-entry float table costs 1 KiB and
 * turns a 43 ns libm call (V8 measurement, see perfbench/js/bench_math_lut.js) into a ~1 ns array
 * read. Nothing can go stale - the mapping is a pure function of the byte value - and it has no
 * per-call allocation.
 *
 * The tables live in GeneratedGammaTables as 2 x 256 source-embedded float constants, produced at
 * development time by perfbench/gen_luts.py. One table matches strict Java float semantics
 * (HotSpot/desktop), the other matches TeaVM 0.9.2's double-lowered float semantics (Chromium/V8);
 * GeneratedGammaTables selects the right constant array once at class init through the engine's
 * EagRuntime.getPlatformType(). There is no static loop and no Math.pow at class initialization
 * (which also removes 256 libm calls from browser startup); TeaVM lowers the arrays to Float32Array
 * literals. See perfbench/CROSS_RUNTIME.md for the generator contract, the measured reason two
 * tables are required, and the regeneration/verification commands.
 *
 * Exactness: each runtime's decode entries are produced with the identical expression that
 * runtime used: strict Java float division and narrowing on HotSpot, TeaVM's double-lowered
 * float division in V8. The encode steps use exact binary64 threshold arrays and max-span-1
 * 513-entry sqrt(x) bucket index arrays generated by perfbench/gen_luts.py: zero approximation,
 * zero loops, at most one comparison per channel, and 0 output bytes changed across all 256^4
 * 4-texel combinations on both HotSpot and TeaVM/V8 (verified exhaustively and differentially
 * in perfbench.VerifyGammaLut). See perfbench/FINDINGS.md and perfbench/CROSS_RUNTIME.md.
 */
public final class MipmapGammaBlend {

	/**
	 * Stable final references to the platform-selected constant arrays. Keeping the references
	 * here lets HotSpot and TeaVM ADVANCED inline lookups into single typed-array loads without
	 * cross-class call overhead.
	 */
	private static final float[] GAMMA = GeneratedGammaTables.activeTable();
	private static final double[] THRESH_BLEND = GeneratedGammaTables.blendThresholds();
	private static final short[] BUCKET_BLEND = GeneratedGammaTables.blendBuckets();
	private static final double[] THRESH_COMP = GeneratedGammaTables.componentThresholds();
	private static final short[] BUCKET_COMP = GeneratedGammaTables.componentBuckets();

	private MipmapGammaBlend() {
	}

	private static int encodeBlend(double x) {
		if (x <= 0.0D) {
			return 0;
		}
		if (x >= 1.0D) {
			return 255;
		}
		int c = BUCKET_BLEND[(int) (Math.sqrt(x) * 512.0D)];
		if (c >= 0) {
			return c;
		}
		int lo = -1 - c;
		return x >= THRESH_BLEND[lo + 1] ? lo + 1 : lo;
	}

	private static int encodeComponent(double x) {
		if (x <= 0.0D) {
			return 0;
		}
		if (x >= 1.0D) {
			return 255;
		}
		int c = BUCKET_COMP[(int) (Math.sqrt(x) * 512.0D)];
		if (c >= 0) {
			return c;
		}
		int lo = -1 - c;
		return x >= THRESH_COMP[lo + 1] ? lo + 1 : lo;
	}

	/**
	 * Blends four ARGB texels into one. {@code gammaCorrect} selects the linear-light average used
	 * when the sprite contains transparency (identical to vanilla's {@code blendColors}).
	 */
	public static int blend(int parInt1, int parInt2, int parInt3, int parInt4, boolean gammaCorrect) {
		if (gammaCorrect) {
			return blendGamma(parInt1, parInt2, parInt3, parInt4);
		}
		final float[] g = GAMMA;
		int i1 = encodeComponent((double) (g[parInt1 >>> 24] + g[parInt2 >>> 24] + g[parInt3 >>> 24] + g[parInt4 >>> 24]) * 0.25D);
		int j1 = encodeComponent((double) (g[parInt1 >> 16 & 255] + g[parInt2 >> 16 & 255] + g[parInt3 >> 16 & 255] + g[parInt4 >> 16 & 255]) * 0.25D);
		int k1 = encodeComponent((double) (g[parInt1 >> 8 & 255] + g[parInt2 >> 8 & 255] + g[parInt3 >> 8 & 255] + g[parInt4 >> 8 & 255]) * 0.25D);
		int l1 = encodeComponent((double) (g[parInt1 & 255] + g[parInt2 & 255] + g[parInt3 & 255] + g[parInt4 & 255]) * 0.25D);
		return i1 << 24 | j1 << 16 | k1 << 8 | l1;
	}

	private static int blendGamma(int parInt1, int parInt2, int parInt3, int parInt4) {
		final float[] g = GAMMA;
		float f = 0.0F;
		float f1 = 0.0F;
		float f2 = 0.0F;
		float f3 = 0.0F;

		int a1 = parInt1 >>> 24;
		if (a1 != 0) {
			f += g[a1];
			f1 += g[parInt1 >> 16 & 255];
			f2 += g[parInt1 >> 8 & 255];
			f3 += g[parInt1 & 255];
		}
		int a2 = parInt2 >>> 24;
		if (a2 != 0) {
			f += g[a2];
			f1 += g[parInt2 >> 16 & 255];
			f2 += g[parInt2 >> 8 & 255];
			f3 += g[parInt2 & 255];
		}
		int a3 = parInt3 >>> 24;
		if (a3 != 0) {
			f += g[a3];
			f1 += g[parInt3 >> 16 & 255];
			f2 += g[parInt3 >> 8 & 255];
			f3 += g[parInt3 & 255];
		}
		int a4 = parInt4 >>> 24;
		if (a4 != 0) {
			f += g[a4];
			f1 += g[parInt4 >> 16 & 255];
			f2 += g[parInt4 >> 8 & 255];
			f3 += g[parInt4 & 255];
		}

		int i2 = encodeBlend((double) (f / 4.0F));
		int j = encodeBlend((double) (f1 / 4.0F));
		int k = encodeBlend((double) (f2 / 4.0F));
		int l = encodeBlend((double) (f3 / 4.0F));
		if (i2 < 96) {
			i2 = 0;
		}

		return i2 << 24 | j << 16 | k << 8 | l;
	}

	/** Blends one channel (selected by {@code shift}) of four ARGB texels, in linear light. */
	public static int blendComponent(int parInt1, int parInt2, int parInt3, int parInt4, int shift) {
		final float[] g = GAMMA;
		float f = g[parInt1 >> shift & 255];
		float f1 = g[parInt2 >> shift & 255];
		float f2 = g[parInt3 >> shift & 255];
		float f3 = g[parInt4 >> shift & 255];
		return encodeComponent((double) (f + f1 + f2 + f3) * 0.25D);
	}

	/** The raw decode table, exposed for the exhaustive equivalence check in perfbench. */
	public static float gamma22(int byteValue) {
		return GAMMA[byteValue & 255];
	}

}
