#!/usr/bin/env node
/*
 * Development-time generator for the WebAssembly proof of concept. Produces a WAT module with
 * 256 source-embedded float32 gamma constants (the same TeaVM/browser variant used in production).
 * No runtime-generated tables and no file loads inside the WASM module: the bytes are a data segment.
 *
 *   node ./perfbench/wasm/gen_wat.js
 *   node ./perfbench/wasm/gen_wat.js --check
 */
'use strict';

const fs = require('fs');
const path = require('path');

const outPath = path.join(__dirname, 'math.wat');
const table = new Float32Array(256);
const bytes = Buffer.alloc(256 * 4);
for (let i = 0; i < 256; ++i) {
  table[i] = Math.fround(Math.pow(i / 255, 2.2));
  bytes.writeFloatLE(table[i], i * 4);
}
const dataLiteral = Array.from(bytes, (b) => '\\' + b.toString(16).padStart(2, '0')).join('');

const wat = `;; Generated by gen_wat.js - DO NOT EDIT. Values: Math.fround(Math.pow(i/255, 2.2)).
;; This is a small, isolated prototype: it DOES NOT transpile the game to WASM.
(module
  ;; JS Math.pow is imported because MVP WASM has no f64.pow instruction. The prototype
  ;; measures both the exact pow path and the table path, including this boundary cost.
  (import "env" "pow" (func $pow (param f64 f64) (result f64)))
  (memory (export "memory") 16) ;; 1 MiB: table at 0, inputs at 65536, outputs at 327680

  ;; 256 float32 constants, little-endian, at byte offset 0 (1024 bytes).
  (data (i32.const 0) "${dataLiteral}")

  ;; One fine-grained call: JS -> WASM -> JS Math.pow -> WASM -> JS.
  (func (export "gamma_pow_f32") (param $v i32) (result f64)
    (f64.promote_f32
      (f32.demote_f64
        (call $pow
          (f64.div (f64.convert_i32_u
            (i32.and (local.get $v) (i32.const 255))) (f64.const 255))
          (f64.const 2.2)))))

  ;; One fine-grained call: JS -> WASM -> f32 table load -> JS.
  (func (export "gamma_lut_f32") (param $v i32) (result f64)
    (f64.promote_f32
      (f32.load (i32.shl (i32.and (local.get $v) (i32.const 255)) (i32.const 2)))))

  ;; Coarse-grained boundary: batch_pow_f32 still imports Math.pow once per element.
  ;; $in is an i32 byte array, $out is an f64 array. Returns a checksum to keep work live.
  (func (export "batch_pow_f32") (param $in i32) (param $n i32) (param $out i32) (result f64)
    (local $i i32) (local $v i32) (local $r f64) (local $sum f64)
    (block $exit
      (loop $loop
        (br_if $exit (i32.ge_u (local.get $i) (local.get $n)))
        (local.set $v (i32.load (i32.add (local.get $in) (i32.shl (local.get $i) (i32.const 2)))))
        (local.set $r (f64.promote_f32
          (f32.demote_f64
            (call $pow
              (f64.div (f64.convert_i32_u
                (i32.and (local.get $v) (i32.const 255))) (f64.const 255))
              (f64.const 2.2)))))
        (f64.store (i32.add (local.get $out) (i32.shl (local.get $i) (i32.const 3))) (local.get $r))
        (local.set $sum (f64.add (local.get $sum) (local.get $r)))
        (local.set $i (i32.add (local.get $i) (i32.const 1)))
        (br $loop)))
    (local.get $sum))

  ;; Coarse-grained boundary: one JS -> WASM call, no JS callbacks, no data copies per op.
  (func (export "batch_lut_f32") (param $in i32) (param $n i32) (param $out i32) (result f64)
    (local $i i32) (local $v i32) (local $r f64) (local $sum f64)
    (block $exit
      (loop $loop
        (br_if $exit (i32.ge_u (local.get $i) (local.get $n)))
        (local.set $v (i32.load (i32.add (local.get $in) (i32.shl (local.get $i) (i32.const 2)))))
        (local.set $r (f64.promote_f32
          (f32.load (i32.shl (i32.and (local.get $v) (i32.const 255)) (i32.const 2)))))
        (f64.store (i32.add (local.get $out) (i32.shl (local.get $i) (i32.const 3))) (local.get $r))
        (local.set $sum (f64.add (local.get $sum) (local.get $r)))
        (local.set $i (i32.add (local.get $i) (i32.const 1)))
        (br $loop)))
    (local.get $sum))
)
`;

if (process.argv.includes('--check')) {
  if (!fs.existsSync(outPath) || fs.readFileSync(outPath, 'utf8') !== wat) {
    console.error('math.wat is missing or differs from generator output; run gen_wat.js');
    process.exit(1);
  }
  console.log('math.wat IDENTICAL');
} else {
  fs.mkdirSync(__dirname, { recursive: true });
  fs.writeFileSync(outPath, wat);
  console.log('wrote ' + outPath + ' (' + Buffer.byteLength(wat) + ' bytes, 256 f32 constants)');
}
